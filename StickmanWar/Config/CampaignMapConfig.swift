    /// O(1) 城关节点字典索引
    public static let byId: [String: CampaignNodeConfig] = {
        Dictionary(uniqueKeysWithValues: allNodes.map { ($0.id, $0) })
    }()

    /// 全图去重后的 78 条无向双向道路列表（按字典序稳定排序，供战略大地图渲染与单元测试使用）
    public static let allRoadEdges: [CampaignRoadEdge] = {
        var edgeSet = Set<CampaignRoadEdge>()
        for node in allNodes {
            for neighborId in node.neighbors {
                edgeSet.insert(CampaignRoadEdge(nodeA: node.id, nodeB: neighborId))
            }
        }
        return edgeSet.sorted { $0.id < $1.id }
    }()

    /// 按节点 ID 查询静态配置
    public static func node(byId nodeId: String) -> CampaignNodeConfig? {
        byId[nodeId]
    }

    /// 获取某势力开局控制的全部城关节点（每势力均衡 5 座）
    public static func initialNodes(for factionId: FactionId) -> [CampaignNodeConfig] {
        allNodes.filter { $0.initialOwner == factionId }
    }
