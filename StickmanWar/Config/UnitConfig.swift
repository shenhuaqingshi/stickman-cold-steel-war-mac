    /// O(1) 兵种字典索引
    public static let byId: [UnitTypeId: UnitStaticStats] = {
        Dictionary(uniqueKeysWithValues: allUnits.map { ($0.id, $0) })
    }()

    /// 按兵种 ID 检索静态配置
    public static func stats(for unitId: UnitTypeId) -> UnitStaticStats? {
        byId[unitId]
    }

    /// 获取指定势力可合法招募的兵种列表（注意：苍狼汗国按势力法则禁造配重投石车）
    public static func recruitableUnits(for factionId: FactionId) -> [UnitStaticStats] {
        allUnits.filter { unit in
            if factionId == .canglang && unit.id == .trebuchet {
                return false
            }
            return unit.exclusiveFaction == nil || unit.exclusiveFaction == factionId
        }
    }
